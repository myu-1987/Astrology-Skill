#!/usr/bin/env python3
"""Read a generated chart JSON and report the Vimshottari Dasha running on a
given date (default: today), plus upcoming period transitions.

Uses jyotishganit's native 3-level dasha tree (Mahadasha -> Antardasha ->
Pratyantardasha, ISO "YYYY-MM-DD" dates) as the primary source. If the chart
also has vedicastro KP data, its 2-level Maha/Bhukti (dates as "dd-mm-yyyy",
a different format - handled separately here, not assumed uniform) is shown
as a cross-check; both follow the same Vimshottari algorithm from the Moon's
nakshatra, so the Mahadasha/Antardasha lords should normally agree between
the two, though exact transition days can differ slightly due to each
library's own Moon-longitude precision.

Usage:
    python analyze_dasha.py --chart Charts/sample-person-chart.json --date 2024-03-15
    python analyze_dasha.py --chart Charts/sample-person-chart.json --period next-year
"""

from __future__ import annotations

import argparse
import sys
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _engine.chart_io import load_chart


def _parse_iso(d: str) -> date:
    return datetime.strptime(d, "%Y-%m-%d").date()


def _parse_ddmmyyyy(d: str) -> date:
    return datetime.strptime(d, "%d-%m-%Y").date()


def find_current_period(mahadashas: dict[str, Any], target: date) -> dict[str, Any] | None:
    for maha_lord, maha in mahadashas.items():
        maha_start, maha_end = _parse_iso(maha["start"]), _parse_iso(maha["end"])
        if not (maha_start <= target <= maha_end):
            continue
        result = {"mahadasha": maha_lord, "start": maha["start"], "end": maha["end"]}
        antardashas = maha.get("antardashas", {})
        for antar_lord, antar in antardashas.items():
            antar_start, antar_end = _parse_iso(antar["start"]), _parse_iso(antar["end"])
            if not (antar_start <= target <= antar_end):
                continue
            result["antardasha"] = {"lord": antar_lord, "start": antar["start"], "end": antar["end"]}
            pratyantardashas = antar.get("pratyantardashas", {})
            for praty_lord, praty in pratyantardashas.items():
                praty_start, praty_end = _parse_iso(praty["start"]), _parse_iso(praty["end"])
                if praty_start <= target <= praty_end:
                    result["pratyantardasha"] = {"lord": praty_lord, "start": praty["start"], "end": praty["end"]}
                    break
            break
        return result
    return None


def find_current_kp_bhukti(kp_dasha: dict[str, Any], target: date) -> dict[str, Any] | None:
    for maha_lord, maha in kp_dasha.items():
        maha_start, maha_end = _parse_ddmmyyyy(maha["start"]), _parse_ddmmyyyy(maha["end"])
        if not (maha_start <= target <= maha_end):
            continue
        result = {"mahadasha": maha_lord, "start": maha["start"], "end": maha["end"]}
        for bhukti_lord, bhukti in maha.get("bhuktis", {}).items():
            b_start, b_end = _parse_ddmmyyyy(bhukti["start"]), _parse_ddmmyyyy(bhukti["end"])
            if b_start <= target <= b_end:
                result["bhukti"] = {"lord": bhukti_lord, "start": bhukti["start"], "end": bhukti["end"]}
                break
        return result
    return None


def upcoming_antardashas(mahadashas: dict[str, Any], window_start: date, window_end: date) -> list[dict[str, Any]]:
    upcoming = []
    for maha_lord, maha in mahadashas.items():
        for antar_lord, antar in maha.get("antardashas", {}).items():
            antar_start = _parse_iso(antar["start"])
            if window_start <= antar_start <= window_end:
                upcoming.append({
                    "mahadasha": maha_lord, "antardasha": antar_lord,
                    "start": antar["start"], "end": antar["end"],
                })
    upcoming.sort(key=lambda row: row["start"])
    return upcoming


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--chart", required=True, help="Path to a chart JSON generated by generate_chart.py")
    parser.add_argument("--date", default=None, help="YYYY-MM-DD; defaults to today")
    parser.add_argument("--period", choices=["next-year"], default=None, help="List upcoming Antardasha transitions")
    args = parser.parse_args()

    chart = load_chart(args.chart)
    target = _parse_iso(args.date) if args.date else date.today()
    mahadashas = (chart.get("dashas") or {}).get("all", {}).get("mahadashas", {})
    if not mahadashas:
        print("No dasha data in this chart file.", file=sys.stderr)
        sys.exit(1)

    current = find_current_period(mahadashas, target)
    print(f"As of {target.isoformat()}:")
    if current:
        print(f"  Mahadasha: {current['mahadasha']} ({current['start']} to {current['end']})")
        if "antardasha" in current:
            a = current["antardasha"]
            print(f"  Antardasha: {a['lord']} ({a['start']} to {a['end']})")
        if "pratyantardasha" in current:
            p = current["pratyantardasha"]
            print(f"  Pratyantardasha: {p['lord']} ({p['start']} to {p['end']})")
    else:
        print("  No matching period found (date may be outside the computed dasha range).")

    kp_dasha = (chart.get("kp_data") or {}).get("vimshottari_maha_bhukti")
    if kp_dasha:
        kp_current = find_current_kp_bhukti(kp_dasha, target)
        if kp_current:
            print(f"\n  [KP cross-check] Mahadasha: {kp_current['mahadasha']} "
                  f"({kp_current['start']} to {kp_current['end']})")
            if "bhukti" in kp_current:
                b = kp_current["bhukti"]
                print(f"  [KP cross-check] Bhukti: {b['lord']} ({b['start']} to {b['end']})")

    if args.period == "next-year":
        window_end = target + timedelta(days=365)
        print(f"\nUpcoming Antardasha transitions through {window_end.isoformat()}:")
        for row in upcoming_antardashas(mahadashas, target, window_end):
            print(f"  {row['start']} to {row['end']}: {row['mahadasha']} / {row['antardasha']}")


if __name__ == "__main__":
    main()
